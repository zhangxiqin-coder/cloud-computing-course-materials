SECTIONS = (("judge", "判断题"), ("choice", "单项选择题"),
            ("fill", "填空题"), ("essay", "简答题"))


def build(ch_no, d):
    name = d["name"]
    folder = os.path.join(OUT_ROOT, "第%02d章_%s" % (ch_no, name))
    os.makedirs(folder, exist_ok=True)
    tag = "第 %d 章 · %s" % (ch_no, name)

    # ---------- 1. 重难点与易错点 ----------
    b = ['<p class="src">对应 %s</p>' % d["src"]]
    b.append("<h3>一、本章重点（必须掌握）</h3>")
    b.append('<div class="key">')
    for i, t in enumerate(d["key"], 1):
        b.append('<div class="item"><div class="t"><span class="tag k">重点%d</span></div>%s</div>' % (i, t))
    b.append("</div>")
    b.append("<h3>二、本章难点（讲慢一点、配比喻）</h3>")
    b.append('<div class="hard">')
    for i, t in enumerate(d["hard"], 1):
        b.append('<div class="item"><div class="t"><span class="tag h">难点%d</span></div>%s</div>' % (i, t))
    b.append("</div>")
    b.append("<h3>三、易错点（学生常错，务必提前点破）</h3>")
    b.append('<div class="trap">')
    for i, t in enumerate(d["trap"], 1):
        b.append('<div class="item"><div class="t"><span class="tag p">易错%d</span></div>%s</div>' % (i, t))
    b.append("</div>")
    b.append('<div class="box tip"><b>教师提示：</b>建议把「易错点」单独投一屏，讲完知识点后立刻点破，'
             '比事后订正有效得多。</div>')
    open(os.path.join(folder, "重难点与易错点.html"), "w", encoding="utf-8").write(
        page(tag, "重难点与易错点", "\n".join(b), tag))

    # ---------- 2. 随堂练习（只有题目） ----------
    q = d["quiz"]
    total = sum(len(q.get(k) or []) for k, _ in SECTIONS)
    b = ['<p class="src">%s</p>' % q.get("src", "")]
    b.append('<p class="src">共 %d 题　｜　答案见《随堂练习_答案.html》</p>' % total)
    CN = "一二三四五六"
    n = 0
    for key, name in SECTIONS:
        items = q.get(key) or []
        if not items:
            continue
        n += 1
        b.append("<h3>%s、%s</h3>" % (CN[n - 1], name))
        for i, x in enumerate(items, 1):
            if key == "choice":
                b.append('<div class="q"><div class="qt">%d. %s</div>%s</div>'
                         % (i, x["q"],
                            "<br>".join('<span class="op">%s</span>' % o for o in x["op"])))
            elif key == "judge":
                b.append('<div class="q"><div class="qt">%d. %s　　（　　）</div></div>'
                         % (i, x["q"]))
            elif key == "essay":
                b.append('<div class="q"><div class="qt">%d. %s</div>'
                         '<div class="exp" style="margin-top:8px">'
                         '（口答或写在纸上，参考答案见答案文档）</div></div>' % (i, x["q"]))
            else:
                b.append('<div class="q"><div class="qt">%d. %s</div></div>' % (i, x["q"]))
    open(os.path.join(folder, "随堂练习.html"), "w", encoding="utf-8").write(
        page(tag, "随堂练习（题目）", "\n".join(b), tag))

    # ---------- 3. 随堂练习_答案 ----------
    b = ['<p class="src">%s</p>' % q.get("src", "")]
    b.append('<p class="src">配套《随堂练习.html》　｜　共 %d 题</p>' % total)
    CN = "一二三四五六"
    n = 0
    for key, name in SECTIONS:
        items = q.get(key) or []
        if not items:
            continue
        n += 1
        b.append("<h3>%s、%s</h3>" % (CN[n - 1], name))
        for i, x in enumerate(items, 1):
            b.append('<div class="q"><div class="qt">%d. %s</div>'
                     '<div class="ans"><b>答案：%s</b></div><div class="exp">%s</div></div>'
                     % (i, x["q"], x["ans"], x["exp"]))
    open(os.path.join(folder, "随堂练习_答案.html"), "w", encoding="utf-8").write(
        page(tag, "随堂练习答案与解析", "\n".join(b), tag))

    # ---------- 4. 上机实操 ----------
    # 第 1-5 章的 上机实操.html 已人工精修（腾讯文档 / Gitee / CloudSim / 特点体验 / 云安全实战），
    # 结构与本脚本的 labs 数据不再一致，此处直接跳过，避免重跑时被覆盖。
    if ch_no in LAB_LOCKED:
        print("  [跳过] 第 %d 章 上机实操.html 为人工精修版，不覆盖" % ch_no)
        return folder
    b = ['<p class="src">机房环境：可上网、不可安装软件，全部实操基于网页 / 在线工具 / 系统自带命令</p>']
    b.append('<div class="box warn"><b>机房纪律：</b>① 一律不安装任何软件，网站要求下载客户端时点「网页版」；'
             '② 涉及云厂商页面<b>只看不买</b>，绝不点付款；③ 下课前必须退出登录，'
             '浏览器问「是否保存密码」一律选「从不」。</div>')
    for i, L in enumerate(d["labs"], 1):
        b.append('<div class="lab">')
        b.append('<div class="lt">%s</div>' % L["name"])
        b.append('<div class="lg"><b>目标：</b>%s</div>' % L["goal"])
        b.append("<b>操作步骤：</b>")
        b.append("<ol>")
        for s in L["steps"]:
            b.append('<li class="step">%s</li>' % s)
        b.append("</ol>")
        b.append("<b>验收清单：</b>")
        b.append('<ul class="chk">')
        for c in L["check"]:
            b.append("<li>%s</li>" % c)
        b.append("</ul>")
        if L.get("warn"):
            b.append('<div class="box warn"><b>打不开 / 完不成：</b>%s</div>' % L["warn"])
        b.append("</div>")
    open(os.path.join(folder, "上机实操.html"), "w", encoding="utf-8").write(
        page(tag, "上机实操指导", "\n".join(b), tag))
    return folder


